"""Generate the Google Apps Script backend for Sheets sync.

Outputs:
  scripts/apps_script/Code.gs         — paste into script.google.com
  scripts/apps_script/INSTRUCTIONS.md — step-by-step deployment guide

The generated script matches src/sync.py's payload shape:
  {action: "upsert", script_secret,
   registros_por_patologia: {key: {headers, codes, rows}}}
plus read/delete actions used by STORE=sheets mode (src/sheets_store.py).
"""

from __future__ import annotations

import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
DICT_PATH = ROOT / "specs" / "data_dictionary.yaml"
OUT_DIR = ROOT / "scripts" / "apps_script"

CODE_TEMPLATE = """\
/**
 * GuOnco Registry — Google Sheets backend (GENERATED by scripts/setup_apps_script.py)
 * One sheet per pathology, named by the stable pathology KEY.
 *
 * Actions (POST JSON body):
 *   upsert        — insert/update rows by _id (safe to re-sync; never duplicates)
 *   get_all       — every record as parsed JSON (from the _json column)
 *   get_record    — one record by _id
 *   delete_record — remove one row by _id
 *
 * SECURITY: set SCRIPT_SECRET below to the same value as SCRIPT_SECRET in the
 * app's .env. Requests without a matching body.script_secret are rejected.
 */
var PATHOLOGIES = __PATHOLOGIES__;
var SCRIPT_SECRET = 'CAMBIA-ESTE-SECRETO / CHANGE-THIS-SECRET';

function doPost(e) {
  var body = JSON.parse(e.postData.contents);
  if (!SCRIPT_SECRET || String(body.script_secret || '') !== SCRIPT_SECRET) {
    return json_({ ok: false, error: 'invalid secret' });
  }
  var action = body.action || 'upsert';
  if (action === 'upsert') return doUpsert_(body);
  if (action === 'get_all') return doGetAll_();
  if (action === 'get_record') return doGetRecord_(body.id);
  if (action === 'delete_record') return doDeleteRecord_(body.id);
  return json_({ ok: false, error: 'unknown action: ' + action });
}

function doUpsert_(body) {
  var data = body.registros_por_patologia || {};
  var ss = SpreadsheetApp.getActiveSpreadsheet();
  var synced = 0;
  Object.keys(data).forEach(function (key) {
    var spec = data[key];
    var sh = ensureSheet_(ss, key);
    ensureHeaders_(sh, spec.headers);
    var index = rowIndexById_(sh);
    spec.rows.forEach(function (row) {
      var rid = String(row[0]);
      if (index[rid]) {
        sh.getRange(index[rid], 1, 1, row.length).setValues([row]);
      } else {
        sh.appendRow(row);
        index[rid] = sh.getLastRow();
      }
      synced++;
    });
  });
  return json_({ ok: true, synced: synced });
}

function doGetAll_() {
  var ss = SpreadsheetApp.getActiveSpreadsheet();
  var out = [];
  ss.getSheets().forEach(function (sh) {
    var parsed = parseSheetRecords_(sh);
    parsed.forEach(function (entry) { out.push(entry); });
  });
  return json_({ ok: true, registros: out });
}

function doGetRecord_(id) {
  var ss = SpreadsheetApp.getActiveSpreadsheet();
  var sheets = ss.getSheets();
  for (var i = 0; i < sheets.length; i++) {
    var entries = parseSheetRecords_(sheets[i]);
    for (var j = 0; j < entries.length; j++) {
      if (String(entries[j].record._id) === String(id)) {
        return json_({ ok: true, found: true,
          key: entries[j].key, record: entries[j].record });
      }
    }
  }
  return json_({ ok: true, found: false });
}

function doDeleteRecord_(id) {
  var ss = SpreadsheetApp.getActiveSpreadsheet();
  var sheets = ss.getSheets();
  for (var i = 0; i < sheets.length; i++) {
    var sh = sheets[i];
    var index = rowIndexById_(sh);
    if (index[String(id)]) {
      sh.deleteRow(index[String(id)]);
      return json_({ ok: true, deleted: true });
    }
  }
  return json_({ ok: true, deleted: false });
}

/* Reads each sheet row back into its raw-code record via the _json column. */
function parseSheetRecords_(sh) {
  var out = [];
  if (sh.getLastRow() < 2) return out;
  var values = sh.getDataRange().getValues();
  var headers = values.shift();
  var jsonCol = headers.indexOf('_json');
  if (jsonCol < 0) return out;
  values.forEach(function (row) {
    var raw = row[jsonCol];
    if (!raw) return;
    try {
      out.push({ key: sh.getName(), record: JSON.parse(raw) });
    } catch (err) { /* skip malformed rows */ }
  });
  return out;
}

function ensureSheet_(ss, name) {
  return ss.getSheetByName(name) || ss.insertSheet(name);
}

function ensureHeaders_(sh, headers) {
  var lastCol = sh.getLastColumn();
  var current = lastCol > 0 ? sh.getRange(1, 1, 1, lastCol).getValues()[0] : [];
  var needsAppend = headers.slice(current.length).filter(function (h) { return h; });
  if (current.length === 0) {
    sh.appendRow(headers);
    sh.setFrozenRows(1);
    sh.getRange(1, 1, 1, headers.length).setFontWeight('bold');
  } else if (needsAppend.length > 0) {
    // Upgrade older deployments: append any missing trailing columns.
    sh.getRange(1, current.length + 1, 1, needsAppend.length).setValues([needsAppend]);
    sh.getRange(1, 1, 1, headers.length).setFontWeight('bold');
  }
}

function rowIndexById_(sh) {
  var index = {};
  var lastRow = sh.getLastRow();
  if (lastRow > 1) {
    sh.getRange(2, 1, lastRow - 1, 1).getValues().forEach(function (r, i) {
      index[String(r[0])] = i + 2;
    });
  }
  return index;
}

function json_(obj) {
  return ContentService.createTextOutput(JSON.stringify(obj))
    .setMimeType(ContentService.MimeType.JSON);
}
"""

INSTRUCTIONS = """\
# Deploying the GuOnco Sheets backend (~5 minutes)

## First deployment

1. Go to <https://sheets.new> and create a blank spreadsheet named
   **GuOnco Registry**.
2. In the spreadsheet: **Extensions → Apps Script**.
3. Delete whatever is in `Code.gs` and paste the full contents of
   `scripts/apps_script/Code.gs` (generated next to this file).
4. **Set your secret**: near the top of `Code.gs`, replace
   `CAMBIA-ESTE-SECRETO / CHANGE-THIS-SECRET` with a long random string,
   then put the SAME value in your `.env`:
   ```
   SCRIPT_SECRET=the-same-long-random-string
   ```
5. Click **Deploy → New deployment → Web app** and set:
   - Description: `GuOnco v2`
   - Execute as: **Me**
   - Who has access: **Anyone**  ← required so your app can POST
6. Click **Deploy**, authorize when prompted, and copy the **Web app URL**
   (ends in `/exec`).
7. Put that URL in your `.env`:
   ```
   APPS_SCRIPT_URL=https://script.google.com/macros/s/XXXX/exec
   ```

## Re-deploying (upgrading from v1)

1. Paste the new `Code.gs` over the old one and **set the secret** (step 4 above).
2. Deploy → **Manage deployments** → Edit → **New version** → Deploy
   (the `/exec` URL stays the same).
3. Existing rows keep working: the script automatically appends the new
   `_creado_por`, `_actualizado_por` and `_json` columns to old sheets.
4. Press **Sincronizar** in the app once so existing records gain their
   `_json` column (needed for reads in `STORE=sheets` mode).

## Notes

- Re-syncing never duplicates: rows are upserted by `_id`.
- Display columns stay human-readable (`CODE (es/en)`); the `_json`
  column stores the raw-code record that the app reads back.
- `registrado_por` attribution shows who captured each case.
- Requests without the shared secret are rejected — keep it private.
"""


def main() -> None:
    data = yaml.safe_load(DICT_PATH.read_text(encoding="utf-8"))
    pathologies = {
        key: {"es": spec["nombre_es"], "en": spec["nombre_en"]}
        for key, spec in data["pathologies"].items()
    }
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    code = CODE_TEMPLATE.replace("__PATHOLOGIES__", repr(pathologies))
    (OUT_DIR / "Code.gs").write_text(code, encoding="utf-8")
    (OUT_DIR / "INSTRUCTIONS.md").write_text(INSTRUCTIONS, encoding="utf-8")
    print(f"wrote {OUT_DIR / 'Code.gs'}")
    print(f"wrote {OUT_DIR / 'INSTRUCTIONS.md'}")


if __name__ == "__main__":
    main()
